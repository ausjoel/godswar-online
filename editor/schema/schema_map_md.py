def _short_reason(r):
    for prefix, short in (("Published content", "published content, hash-checked at start-up."),
                          ("Immutable evidence", "immutable evidence (triggers)."),
                          ("Sealed balance revision", "sealed balance revision (triggers); change = new revision + pointer move + restart."),
                          ("Exactly-once evidence", "exactly-once claim evidence."),
                          ("Append-only audit", "append-only audit."),
                          ("Authoring / staging copy", "staging copy; the server runs the published rows."),
                          ("Reference copy", "reference copy; the server does not read it.")):
        if r.startswith(prefix):
            return short
    return r


def _esc(s):
    return (s or "").replace("|", "\\|").replace("\n", " ")


def render(doc):
    meta = doc["_meta"]
    tables = {k: v for k, v in doc.items() if not k.startswith("_")}
    out = [INTRO.format(
        tables=meta["table_count"],
        public=sum(1 for t in tables.values() if t["schema"] == "public"),
        columns=meta["column_count"],
        views=len(meta["views"]),
        edit_classes="<br>".join("`%s`: %s" % (k, _esc(v)) for k, v in meta["edit_classes"].items()),
        applies="<br>".join("`%s`: %s" % (k, _esc(v)) for k, v in meta["applies"].items()),
    )]
    out.append("| System | Tables | free | sealed | derived | revision | internal |\n|---|---:|---:|---:|---:|---:|---:|")
    for key, title in SYSTEM_ORDER:
        names = meta["systems"].get(key, [])
        cnt = {c: sum(1 for n in names if tables[n]["edit_class"] == c)
               for c in ("free", "sealed", "derived", "revision", "internal")}
        out.append("| %s | %d | %d | %d | %d | %d | %d |" % (title, len(names), cnt["free"], cnt["sealed"],
                                                          cnt["derived"], cnt["revision"], cnt["internal"]))
    out.append("")
    for key, title in SYSTEM_ORDER:
        names = sorted(meta["systems"].get(key, []), key=lambda n: (
            ["free", "revision", "derived", "sealed", "internal"].index(tables[n]["edit_class"]), n))
        out.append("### %s\n" % title)
        if key in NO_TABLE:
            out.append(NO_TABLE[key] + "\n")
        if not names:
            continue
        out.append("| Table | Rows | Class | Applies | What it is | Notes |\n|---|---:|---|---|---|---|")
        for n in names:
            t = tables[n]
            notes = t.get("note") or ""
            if t.get("read_only_reason") and t["edit_class"] in ("sealed", "derived"):
                notes = (notes + " " if notes else "") + "**Read-only:** " + _short_reason(t["read_only_reason"])
            if t["edit_class"] == "derived" and t.get("referenced_by"):
                notes += " Foreign-key target of %s, so ids must exist here." % ", ".join(
                    "`%s`" % r for r in t["referenced_by"][:4]) + (" ..." if len(t["referenced_by"]) > 4 else "")
            out.append("| `%s` | %s | %s | %s | %s | %s |" % (
                n, "" if t["rows_live"] is None else "{:,}".format(t["rows_live"]), t["edit_class"],
                t["applies"], _esc(t["description"]), _esc(notes)))
        out.append("")
    out.append(CLASS_EVIDENCE)
    unknowns = []
    for n, t in tables.items():
        for c, cv in t["columns"].items():
            d = cv["description"].lower()
            if "unknown" in d or "not confirmed" in d:
                unknowns.append("* `%s.%s`: %s" % (n, c, cv["description"]))
    out.append(TAIL.format(unknowns="\n".join(unknowns)))
    return "\n".join(out)

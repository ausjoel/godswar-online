# when a running server reads the table
STARTUP, LOGIN, PER_USE, HOT, NEVER, UNKNOWN = "startup", "login", "per_use", "hot_reload", "never", "unknown"

R_CONTENT = ("Published content: rows belong to a sealed revision whose SHA-256 the server recomputes "
             "at start-up; database triggers reject UPDATE/DELETE. A change needs a new revision plus a "
             "pointer move, then a restart.")
R_EVIDENCE = ("Immutable evidence: database triggers reject UPDATE/DELETE/TRUNCATE, and the server's "
              "ledgers and reconciliation rely on it.")
R_CLAIM = ("Exactly-once evidence: the row is what stops a reward, entry or claim from being paid twice. "
           "Changing or deleting it can pay a reward again or break reconciliation.")
R_BALANCE = ("Sealed balance revision: triggers reject UPDATE/DELETE and inserts into a sealed revision; a change "
             "is a new revision plus a pointer move (validated by trigger), and workers pick it up only at restart.")
R_AUDIT = "Append-only audit written by the server (or by this editor); history is never rewritten."
R_STAGING = ("Authoring / staging copy. The server loads it only into an EMPTY database to build the first "
             "published revision; the running server reads the published *_definitions rows instead, so "
             "editing this table changes nothing in game.")
R_REFERENCE = ("Reference copy of client data (or captured data). The running server does not read it; "
               "the client keeps its own copy, so an edit here would only mislead.")

def T(system, edit_class, applies, description, note=None, reason=None):
    d = {"system": system, "edit_class": edit_class, "applies": applies, "description": description}
    if note:
        d["note"] = note
    if reason:
        d["read_only_reason"] = reason
    return d


using System.Data;
using System.Text.Json;
using Godswar.Server.Infrastructure.Inventory;
using Godswar.Server.State;
using Npgsql;

namespace Godswar.Server.Infrastructure.Trade;

// TRADE: the only writer of player trades and stall purchases. Each call is ONE transaction:
// both character rows are locked in ascending id order (two crossing confirmations cannot
// deadlock), every offered kit-bag row is re-read FOR UPDATE and must still be the row that was
// offered (same instance id, owner, slot, item and stack, not bound, and the same fingerprint of
// every other column, so a row changed in place - Holy Stone, forge, enhancement - is refused),
// wallets and bag space are checked inside the transaction, rows change owner with UPDATE user_id
// (the sealed-pet trigger moves a packed pet with its item and refuses bound ones), the swap is
// logged in player_trade_log, and each character gets the same economy evidence every other
// wallet/bag writer writes (command_audit + command_inbox, currency and inventory ledger rows at
// the new revisions; PlayerTradeStore.Ledger.cs). Any failure rolls the whole thing back: an item
// is never in two bags and never in none.

/// <summary>
/// One offered kit-bag row. <paramref name="Fingerprint"/> is md5 of the row's JSON without
/// slot_index, stack and updated_at (those are checked separately or change on a partial stall sale).
/// </summary>
internal sealed record PlayerTradeItemRef(long InstanceId, int KitBagSlot, uint ItemId, short Stack, string Fingerprint);

internal sealed record PlayerTradeCommitSide(
    int AccountId,
    int CharacterId,
    int Silver,
    int Gold,
    IReadOnlyList<PlayerTradeItemRef> Items);

internal enum PlayerTradeCommitStatus
{
    Committed = 0,
    Unavailable,
    CharacterMissing,
    ItemChanged,
    ItemBound,
    NotEnoughSilver,
    NotEnoughGold,
    WalletOverflow,
    BagFull,
    Failed
}

internal sealed record PlayerTradeCommitResult(
    PlayerTradeCommitStatus Status,
    int? CharacterId = null,
    long? LogId = null,
    string? Detail = null)
{
    public bool Committed => Status == PlayerTradeCommitStatus.Committed;
}

internal sealed record PlayerTradeItemProbe(
    long InstanceId, uint ItemId, short Stack, short Bound, string Fingerprint, CompactItemEntry Item);

internal static partial class PlayerTradeStore
{
    public const short KitBagLocation = 1;
    public const int KitBagSlots = 96;         // KitBagItemGrantPlanner.SlotCount (4 pages x 24)
    private const int StagingSlotBase = 30_000; // location 1 allows slot_index up to 32767

    private static NpgsqlDataSource? _dataSource;
    private static string _copyColumns = string.Empty;

    public static bool Enabled { get; private set; }

    // Fingerprint of everything on the row except what the commit checks on its own (slot, stack)
    // and the touch time. Any in-place change (sockets, grade, attributes, bound, owner) alters it.
    internal const string FingerprintSql =
        "md5((to_jsonb(item) - 'slot_index' - 'stack' - 'updated_at')::text)";

    // NOT a registered schema migration (review finding 3/16): the migration runner needs the
    // applied history to be an exact prefix of the binary's list, so a registered id would stop the
    // previous dll from starting and would clash with other builds' ids. The table is created on
    // first use instead (idempotent; no foreign key, so no lock on character_base), and
    // Development/build/trade/migration.sql holds the same DDL to run before release.
    internal const string PlayerTradeLogDdl = """
        CREATE TABLE IF NOT EXISTS public.player_trade_log (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            kind varchar(16) NOT NULL CHECK (kind IN ('trade', 'stall')),
            first_character_id integer NOT NULL,
            second_character_id integer NOT NULL,
            first_silver integer NOT NULL CHECK (first_silver >= 0),
            first_gold integer NOT NULL CHECK (first_gold >= 0),
            second_silver integer NOT NULL CHECK (second_silver >= 0),
            second_gold integer NOT NULL CHECK (second_gold >= 0),
            first_items jsonb NOT NULL,
            second_items jsonb NOT NULL,
            detail jsonb NOT NULL,
            created_at timestamptz NOT NULL DEFAULT now()
        );
        CREATE INDEX IF NOT EXISTS ix_player_trade_log_first ON public.player_trade_log (first_character_id, created_at);
        CREATE INDEX IF NOT EXISTS ix_player_trade_log_second ON public.player_trade_log (second_character_id, created_at);
        """;

    public static async Task InitializeAsync(string connectionString, CancellationToken cancellationToken = default)
    {
        try
        {
            _dataSource ??= NpgsqlDataSource.Create(connectionString);
            await using (var check = _dataSource.CreateCommand(
                "SELECT to_regclass('public.player_trade_log') IS NOT NULL"))
            {
                Enabled = (bool)(await check.ExecuteScalarAsync(cancellationToken) ?? false);
            }
            if (!Enabled)
            {
                await using var create = _dataSource.CreateCommand(PlayerTradeLogDdl);
                await create.ExecuteNonQueryAsync(cancellationToken);
                Enabled = true;
                Console.WriteLine("[trade] created public.player_trade_log on first use");
            }

            // Columns copied when a stall sale splits a stack. Read from the live table so a later
            // migration that adds an item column is copied too.
            var columns = new List<string>();
            await using (var read = _dataSource.CreateCommand("""
                SELECT column_name FROM information_schema.columns
                WHERE table_schema = 'public' AND table_name = 'character_items'
                  AND column_name NOT IN ('id', 'user_id', 'slot_index', 'stack', 'created_at', 'updated_at')
                ORDER BY ordinal_position
                """))
            await using (var reader = await read.ExecuteReaderAsync(cancellationToken))
            {
                while (await reader.ReadAsync(cancellationToken)) columns.Add(reader.GetString(0));
            }
            _copyColumns = string.Join(", ", columns.Select(static c => "\"" + c.Replace("\"", "\"\"") + "\""));
            Console.WriteLine(Enabled
                ? $"[trade] store ready ({columns.Count} copy columns)"
                : "[trade] store off: player_trade_log is missing (run Development/build/trade/migration.sql)");
        }
        catch (Exception error) when (error is not OperationCanceledException)
        {
            Enabled = false;
            Console.WriteLine($"[trade] store off: start-up check failed: {error.GetType().Name}: {error.Message}");
        }
    }

    public static async Task<PlayerTradeItemProbe?> ProbeKitBagItemAsync(
        int characterId, int kitBagSlot, CancellationToken cancellationToken)
    {
        if (_dataSource is null || kitBagSlot is < 0 or >= KitBagSlots) return null;
        // Same column order as PostgresCompactItemReader expects (WonderlandSackInventory uses it
        // too), so the partner and stall buyers see the database row, not the in-memory copy.
        await using var command = _dataSource.CreateCommand($"""
            SELECT item.item_location,item.slot_index,item.prop_id,
                item.attribute1,item.attribute2,item.attribute3,item.attribute4,item.attribute5,
                item.attribute_level1,item.attribute_level2,item.attribute_level3,item.attribute_level4,item.attribute_level5,
                item.item_quality,item.item_grade,item.bound,item.stack,item.item_exp,item.holy_suit_code,
                item.holy_socket_count,item.holy_socket1_effect_id,item.holy_socket1_level,
                item.holy_socket2_effect_id,item.holy_socket2_level,item.holy_socket3_effect_id,item.holy_socket3_level,
                item.holy_socket4_effect_id,item.holy_socket4_level,item.holy_socket5_effect_id,item.holy_socket5_level,
                item.holy_socket6_effect_id,item.holy_socket6_level,item.class_attribute1,item.class_attribute2,
                item.elemental_attribute1,item.elemental_attribute2,item.holy_socket1_value,item.holy_socket2_value,
                item.holy_socket3_value,item.holy_socket4_value,sealed_link.pet_id,item.id,{FingerprintSql}
            FROM public.character_items item LEFT JOIN public.sealed_pet_items sealed_link
              ON sealed_link.item_instance_id = item.id AND item.prop_id = 10109
             AND sealed_link.owner_character_id = item.user_id
            WHERE item.user_id = @c AND item.item_location = 1 AND item.slot_index = @s
            """);
        command.Parameters.AddWithValue("c", characterId);
        command.Parameters.AddWithValue("s", (short)kitBagSlot);
        await using var reader = await command.ExecuteReaderAsync(cancellationToken);
        if (!await reader.ReadAsync(cancellationToken)) return null;
        return new PlayerTradeItemProbe(
            reader.GetInt64(41), checked((uint)reader.GetInt32(2)), reader.GetInt16(16), reader.GetInt16(15),
            reader.GetString(42), PostgresCompactItemReader.ReadAuthoritativeCompactItem(reader));
    }

    public static async Task<IReadOnlySet<long>> ReadKitBagInstanceIdsAsync(int characterId, CancellationToken cancellationToken)
    {
        var ids = new HashSet<long>();
        if (_dataSource is null) return ids;
        await using var command = _dataSource.CreateCommand(
            "SELECT id FROM public.character_items WHERE user_id = @c AND item_location = 1");
        command.Parameters.AddWithValue("c", characterId);
        await using var reader = await command.ExecuteReaderAsync(cancellationToken);
        while (await reader.ReadAsync(cancellationToken)) ids.Add(reader.GetInt64(0));
        return ids;
    }


    private readonly record struct LockedWallet(int AccountId, int Silver, int Gold, long WalletRevision, long InventoryRevision);

    private static async Task<Dictionary<int, LockedWallet>?> LockWalletsAsync(
        NpgsqlConnection connection, NpgsqlTransaction transaction,
        IReadOnlyList<PlayerTradeCommitSide> sides, CancellationToken cancellationToken)
    {
        var wallets = new Dictionary<int, LockedWallet>();
        foreach (var side in sides.OrderBy(static s => s.CharacterId))
        {
            await using var command = new NpgsqlCommand("""
                SELECT account_id, "Money", "Stone", wallet_revision, inventory_revision FROM public.character_base
                WHERE id = @c AND account_id = @a AND lifecycle_state = 'active' FOR UPDATE
                """, connection, transaction);
            command.Parameters.AddWithValue("c", side.CharacterId);
            command.Parameters.AddWithValue("a", side.AccountId);
            await using var reader = await command.ExecuteReaderAsync(cancellationToken);
            if (!await reader.ReadAsync(cancellationToken)) return null;
            wallets[side.CharacterId] = new LockedWallet(
                reader.GetInt32(0), reader.GetInt32(1), reader.GetInt32(2), reader.GetInt64(3), reader.GetInt64(4));
        }
        return wallets;
    }

    private static async Task<PlayerTradeCommitResult?> VerifyOffersAsync(
        NpgsqlConnection connection, NpgsqlTransaction transaction,
        PlayerTradeCommitSide side, Dictionary<long, string> beforeStates, CancellationToken cancellationToken)
    {
        foreach (var item in side.Items)
        {
            await using var command = new NpgsqlCommand($"""
                SELECT item.user_id, item.item_location, item.slot_index, item.prop_id, item.stack, item.bound,
                       {FingerprintSql}, to_jsonb(item)::text
                FROM public.character_items item WHERE item.id = @id FOR UPDATE
                """, connection, transaction);
            command.Parameters.AddWithValue("id", item.InstanceId);
            await using var reader = await command.ExecuteReaderAsync(cancellationToken);
            if (!await reader.ReadAsync(cancellationToken))
                return new(PlayerTradeCommitStatus.ItemChanged, side.CharacterId, Detail: $"row {item.InstanceId} gone");
            if (reader.GetInt32(0) != side.CharacterId || reader.GetInt16(1) != KitBagLocation ||
                reader.GetInt16(2) != item.KitBagSlot || reader.GetInt32(3) != (int)item.ItemId ||
                reader.GetInt16(4) != item.Stack)
            {
                return new(PlayerTradeCommitStatus.ItemChanged, side.CharacterId, Detail: $"row {item.InstanceId} changed");
            }
            if (reader.GetInt16(5) != 0)
                return new(PlayerTradeCommitStatus.ItemBound, side.CharacterId, Detail: $"row {item.InstanceId} bound");
            // Review finding 2/6/17: any in-place change since the item was offered (sockets, grade,
            // enhancement, attributes) refuses the commit; the partner saw the offered state.
            if (!string.Equals(reader.GetString(6), item.Fingerprint, StringComparison.Ordinal))
                return new(PlayerTradeCommitStatus.ItemChanged, side.CharacterId, Detail: $"row {item.InstanceId} changed in place");
            beforeStates[item.InstanceId] = reader.GetString(7);
        }
        return null;
    }

    private static async Task<HashSet<int>> ReadOccupiedAsync(
        NpgsqlConnection connection, NpgsqlTransaction transaction, int characterId, CancellationToken cancellationToken)
    {
        var occupied = new HashSet<int>();
        await using var command = new NpgsqlCommand("""
            SELECT slot_index FROM public.character_items
            WHERE user_id = @c AND item_location = 1 FOR UPDATE
            """, connection, transaction);
        command.Parameters.AddWithValue("c", characterId);
        await using var reader = await command.ExecuteReaderAsync(cancellationToken);
        while (await reader.ReadAsync(cancellationToken)) occupied.Add(reader.GetInt16(0));
        return occupied;
    }

    internal static List<int> FreeSlots(IReadOnlySet<int> occupied, IEnumerable<int> leaving)
    {
        var gone = leaving.ToHashSet();
        var free = new List<int>();
        for (var slot = 0; slot < KitBagSlots; slot++)
        {
            if (!occupied.Contains(slot) || gone.Contains(slot)) free.Add(slot);
        }
        return free;
    }

    private static async Task MoveRowAsync(
        NpgsqlConnection connection, NpgsqlTransaction transaction,
        long instanceId, int from, int to, int slot, CancellationToken cancellationToken)
    {
        await using var command = new NpgsqlCommand("""
            UPDATE public.character_items
            SET user_id = @to, slot_index = @slot, updated_at = now()
            WHERE id = @id AND user_id = @from AND item_location = 1 AND bound = 0
            """, connection, transaction);
        command.Parameters.AddWithValue("to", to);
        command.Parameters.AddWithValue("slot", (short)slot);
        command.Parameters.AddWithValue("id", instanceId);
        command.Parameters.AddWithValue("from", from);
        if (await command.ExecuteNonQueryAsync(cancellationToken) != 1)
            throw new InvalidOperationException($"Item row {instanceId} did not move exactly once.");
    }

    private static async Task PlaceRowAsync(
        NpgsqlConnection connection, NpgsqlTransaction transaction,
        long instanceId, int owner, int slot, CancellationToken cancellationToken)
    {
        await using var command = new NpgsqlCommand("""
            UPDATE public.character_items SET slot_index = @slot
            WHERE id = @id AND user_id = @owner AND item_location = 1
            """, connection, transaction);
        command.Parameters.AddWithValue("slot", (short)slot);
        command.Parameters.AddWithValue("id", instanceId);
        command.Parameters.AddWithValue("owner", owner);
        if (await command.ExecuteNonQueryAsync(cancellationToken) != 1)
            throw new InvalidOperationException($"Item row {instanceId} was not placed exactly once.");
    }

    private static async Task<long> InsertLogAsync(
        NpgsqlConnection connection, NpgsqlTransaction transaction, string kind,
        PlayerTradeCommitSide first, PlayerTradeCommitSide second, object detail,
        CancellationToken cancellationToken)
    {
        await using var command = new NpgsqlCommand("""
            INSERT INTO public.player_trade_log (
                kind, first_character_id, second_character_id,
                first_silver, first_gold, second_silver, second_gold,
                first_items, second_items, detail)
            VALUES (@kind, @a, @b, @as, @ag, @bs, @bg,
                    @ai::jsonb, @bi::jsonb, @detail::jsonb)
            RETURNING id
            """, connection, transaction);
        command.Parameters.AddWithValue("kind", kind);
        command.Parameters.AddWithValue("a", first.CharacterId);
        command.Parameters.AddWithValue("b", second.CharacterId);
        command.Parameters.AddWithValue("as", first.Silver);
        command.Parameters.AddWithValue("ag", first.Gold);
        command.Parameters.AddWithValue("bs", second.Silver);
        command.Parameters.AddWithValue("bg", second.Gold);
        command.Parameters.AddWithValue("ai", JsonSerializer.Serialize(first.Items));
        command.Parameters.AddWithValue("bi", JsonSerializer.Serialize(second.Items));
        command.Parameters.AddWithValue("detail", JsonSerializer.Serialize(detail));
        return (long)(await command.ExecuteScalarAsync(cancellationToken))!;
    }

    private static async Task<PlayerTradeCommitResult> Refuse(
        NpgsqlTransaction transaction, PlayerTradeCommitStatus status, int characterId, CancellationToken cancellationToken,
        string? detail = null)
    {
        await transaction.RollbackAsync(cancellationToken);
        return new(status, characterId, Detail: detail);
    }

    private static async Task SafeRollbackAsync(NpgsqlTransaction? transaction)
    {
        if (transaction is null) return;
        try { await transaction.RollbackAsync(CancellationToken.None); }
        catch (Exception) { /* the connection is gone; the server rolls back on its own */ }
    }

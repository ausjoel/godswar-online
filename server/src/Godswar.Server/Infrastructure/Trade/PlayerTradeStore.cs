    public static async Task<PlayerTradeCommitResult> CommitTradeAsync(
        PlayerTradeCommitSide first,
        PlayerTradeCommitSide second,
        CancellationToken cancellationToken)
    {
        if (_dataSource is null || !Enabled) return new(PlayerTradeCommitStatus.Unavailable);
        if (first.CharacterId == second.CharacterId || first.Silver < 0 || first.Gold < 0 ||
            second.Silver < 0 || second.Gold < 0)
        {
            return new(PlayerTradeCommitStatus.Failed, Detail: "invalid request");
        }

        NpgsqlConnection? connection = null;
        NpgsqlTransaction? transaction = null;
        try
        {
            // Inside the try (review finding 4): a pool timeout or a database restart returns
            // Failed instead of throwing past the caller's clean-up.
            connection = await _dataSource.OpenConnectionAsync(cancellationToken);
            transaction = await connection.BeginTransactionAsync(IsolationLevel.ReadCommitted, cancellationToken);
            var wallets = await LockWalletsAsync(connection, transaction, [first, second], cancellationToken);
            if (wallets is null)
            {
                await transaction.RollbackAsync(cancellationToken);
                return new(PlayerTradeCommitStatus.CharacterMissing);
            }
            foreach (var side in new[] { first, second }.OrderBy(static s => s.CharacterId))
            {
                if (!await EnsureBaselineAsync(connection, transaction, side.AccountId, side.CharacterId, cancellationToken))
                    return await Refuse(transaction, PlayerTradeCommitStatus.Failed, side.CharacterId, cancellationToken, "economy baseline missing");
            }

            var beforeStates = new Dictionary<long, string>();
            foreach (var side in new[] { first, second })
            {
                var refusal = await VerifyOffersAsync(connection, transaction, side, beforeStates, cancellationToken);
                if (refusal is not null)
                {
                    await transaction.RollbackAsync(cancellationToken);
                    return refusal;
                }
            }

            var a = wallets[first.CharacterId];
            var b = wallets[second.CharacterId];
            if (a.Silver < first.Silver) return await Refuse(transaction, PlayerTradeCommitStatus.NotEnoughSilver, first.CharacterId, cancellationToken);
            if (b.Silver < second.Silver) return await Refuse(transaction, PlayerTradeCommitStatus.NotEnoughSilver, second.CharacterId, cancellationToken);
            if (a.Gold < first.Gold) return await Refuse(transaction, PlayerTradeCommitStatus.NotEnoughGold, first.CharacterId, cancellationToken);
            if (b.Gold < second.Gold) return await Refuse(transaction, PlayerTradeCommitStatus.NotEnoughGold, second.CharacterId, cancellationToken);
            var aSilver = (long)a.Silver - first.Silver + second.Silver;
            var bSilver = (long)b.Silver - second.Silver + first.Silver;
            var aGold = (long)a.Gold - first.Gold + second.Gold;
            var bGold = (long)b.Gold - second.Gold + first.Gold;
            if (aSilver > int.MaxValue || aGold > int.MaxValue)
                return await Refuse(transaction, PlayerTradeCommitStatus.WalletOverflow, first.CharacterId, cancellationToken);
            if (bSilver > int.MaxValue || bGold > int.MaxValue)
                return await Refuse(transaction, PlayerTradeCommitStatus.WalletOverflow, second.CharacterId, cancellationToken);

            // Free slots after the swap: today's empty slots plus the ones this side gives away.
            var occupiedA = await ReadOccupiedAsync(connection, transaction, first.CharacterId, cancellationToken);
            var occupiedB = await ReadOccupiedAsync(connection, transaction, second.CharacterId, cancellationToken);
            var freeA = FreeSlots(occupiedA, first.Items.Select(static i => i.KitBagSlot));
            var freeB = FreeSlots(occupiedB, second.Items.Select(static i => i.KitBagSlot));
            if (freeA.Count < second.Items.Count)
                return await Refuse(transaction, PlayerTradeCommitStatus.BagFull, first.CharacterId, cancellationToken);
            if (freeB.Count < first.Items.Count)
                return await Refuse(transaction, PlayerTradeCommitStatus.BagFull, second.CharacterId, cancellationToken);

            // Stage every moving row on a slot nobody uses (ux_character_items_location_slot is not
            // deferrable), then give each its final slot in the receiver's bag.
            var staged = new List<(long Id, int To, int Slot)>();
            var stage = StagingSlotBase;
            foreach (var item in first.Items)
            {
                await MoveRowAsync(connection, transaction, item.InstanceId, first.CharacterId, second.CharacterId, stage, cancellationToken);
                staged.Add((item.InstanceId, second.CharacterId, stage++));
            }
            foreach (var item in second.Items)
            {
                await MoveRowAsync(connection, transaction, item.InstanceId, second.CharacterId, first.CharacterId, stage, cancellationToken);
                staged.Add((item.InstanceId, first.CharacterId, stage++));
            }
            var nextA = 0;
            var nextB = 0;
            var placed = new List<object>();
            foreach (var (id, to, _) in staged)
            {
                var slot = to == first.CharacterId ? freeA[nextA++] : freeB[nextB++];
                await PlaceRowAsync(connection, transaction, id, to, slot, cancellationToken);
                placed.Add(new { id, to, slot });
            }
            var afterStates = await ReadStatesAsync(connection, transaction, staged.Select(static s => s.Id), cancellationToken);

            // Evidence (review finding 1/13): giver 'delete', receiver 'add', currency rows at the
            // new wallet revision, both revisions advanced exactly once and only when they changed.
            var tradeId = Guid.NewGuid();
            await WriteCharacterEvidenceAsync(connection, transaction, TradeFamily, tradeId,
                first.AccountId, first.CharacterId, second.CharacterId, a, (int)aSilver, (int)aGold,
                EntriesFor(first, second, beforeStates, afterStates), cancellationToken);
            await WriteCharacterEvidenceAsync(connection, transaction, TradeFamily, tradeId,
                second.AccountId, second.CharacterId, first.CharacterId, b, (int)bSilver, (int)bGold,
                EntriesFor(second, first, beforeStates, afterStates), cancellationToken);

            var logId = await InsertLogAsync(connection, transaction, "trade", first, second, new
            {
                tradeId,
                first = new { first.CharacterId, silverBefore = a.Silver, silverAfter = aSilver, goldBefore = a.Gold, goldAfter = aGold },
                second = new { second.CharacterId, silverBefore = b.Silver, silverAfter = bSilver, goldBefore = b.Gold, goldAfter = bGold },
                placed
            }, cancellationToken);
            await transaction.CommitAsync(cancellationToken);
            return new(PlayerTradeCommitStatus.Committed, LogId: logId);
        }
        catch (PostgresException error) when (error.SqlState is "23514" or "40001" or "40P01" or "23505")
        {
            await SafeRollbackAsync(transaction);
            return new(PlayerTradeCommitStatus.Failed, Detail: $"{error.SqlState} {error.MessageText}");
        }
        catch (Exception error) when (error is not OperationCanceledException)
        {
            await SafeRollbackAsync(transaction);
            return new(PlayerTradeCommitStatus.Failed, Detail: $"{error.GetType().Name}: {error.Message}");
        }
        finally
        {
            if (transaction is not null) await transaction.DisposeAsync();
            if (connection is not null) await connection.DisposeAsync();
        }
    }

    // ---- stall purchase ---------------------------------------------------------------------

    /// <summary>
    /// Buys <paramref name="quantity"/> units of one stall item. The whole stack moves when every
    /// unit is bought; otherwise the seller's stack shrinks and the buyer gets a copy of the row
    /// with the bought quantity (all item columns copied). Price is per unit.
    /// </summary>
    public static async Task<PlayerTradeCommitResult> CommitStallPurchaseAsync(
        int sellerAccountId, int sellerId, PlayerTradeItemRef item,
        int buyerAccountId, int buyerId, int quantity, int silverPerUnit, int goldPerUnit,
        CancellationToken cancellationToken)
    {
        if (_dataSource is null || !Enabled) return new(PlayerTradeCommitStatus.Unavailable);
        if (sellerId == buyerId || quantity <= 0 || quantity > item.Stack || silverPerUnit < 0 || goldPerUnit < 0)
            return new(PlayerTradeCommitStatus.Failed, Detail: "invalid request");
        var silverCost = (long)silverPerUnit * quantity;
        var goldCost = (long)goldPerUnit * quantity;
        if (silverCost > int.MaxValue || goldCost > int.MaxValue)
            return new(PlayerTradeCommitStatus.WalletOverflow, buyerId);

        var seller = new PlayerTradeCommitSide(sellerAccountId, sellerId, 0, 0, [item]);
        var buyer = new PlayerTradeCommitSide(buyerAccountId, buyerId, (int)silverCost, (int)goldCost, []);
        NpgsqlConnection? connection = null;
        NpgsqlTransaction? transaction = null;
        try
        {
            connection = await _dataSource.OpenConnectionAsync(cancellationToken);
            transaction = await connection.BeginTransactionAsync(IsolationLevel.ReadCommitted, cancellationToken);
            var wallets = await LockWalletsAsync(connection, transaction, [seller, buyer], cancellationToken);
            if (wallets is null)
            {
                await transaction.RollbackAsync(cancellationToken);
                return new(PlayerTradeCommitStatus.CharacterMissing);
            }
            foreach (var side in new[] { seller, buyer }.OrderBy(static s => s.CharacterId))
            {
                if (!await EnsureBaselineAsync(connection, transaction, side.AccountId, side.CharacterId, cancellationToken))
                    return await Refuse(transaction, PlayerTradeCommitStatus.Failed, side.CharacterId, cancellationToken, "economy baseline missing");
            }
            var beforeStates = new Dictionary<long, string>();
            var refusal = await VerifyOffersAsync(connection, transaction, seller, beforeStates, cancellationToken);
            if (refusal is not null)
            {
                await transaction.RollbackAsync(cancellationToken);
                return refusal;
            }
            var s = wallets[sellerId];
            var b = wallets[buyerId];
            if (b.Silver < silverCost) return await Refuse(transaction, PlayerTradeCommitStatus.NotEnoughSilver, buyerId, cancellationToken);
            if (b.Gold < goldCost) return await Refuse(transaction, PlayerTradeCommitStatus.NotEnoughGold, buyerId, cancellationToken);
            if (s.Silver + silverCost > int.MaxValue || s.Gold + goldCost > int.MaxValue)
                return await Refuse(transaction, PlayerTradeCommitStatus.WalletOverflow, sellerId, cancellationToken);
            var free = FreeSlots(await ReadOccupiedAsync(connection, transaction, buyerId, cancellationToken), []);
            if (free.Count == 0) return await Refuse(transaction, PlayerTradeCommitStatus.BagFull, buyerId, cancellationToken);
            var slot = free[0];

            List<InventoryEntry> sellerEntries;
            List<InventoryEntry> buyerEntries;
            if (quantity == item.Stack)
            {
                await MoveRowAsync(connection, transaction, item.InstanceId, sellerId, buyerId, slot, cancellationToken);
                var after = await ReadStatesAsync(connection, transaction, [item.InstanceId], cancellationToken);
                sellerEntries = [new(item.InstanceId, "delete", beforeStates[item.InstanceId], null)];
                buyerEntries = [new(item.InstanceId, "add", null, after[item.InstanceId])];
            }
            else
            {
                await using (var shrink = new NpgsqlCommand("""
                    UPDATE public.character_items SET stack = stack - @q, updated_at = now()
                    WHERE id = @id AND user_id = @seller AND item_location = 1 AND stack = @before
                    """, connection, transaction))
                {
                    shrink.Parameters.AddWithValue("q", (short)quantity);
                    shrink.Parameters.AddWithValue("id", item.InstanceId);
                    shrink.Parameters.AddWithValue("seller", sellerId);
                    shrink.Parameters.AddWithValue("before", item.Stack);
                    if (await shrink.ExecuteNonQueryAsync(cancellationToken) != 1)
                        throw new InvalidOperationException("The stall stack changed while it was being split.");
                }
                long newId;
                await using (var copy = new NpgsqlCommand($"""
                    INSERT INTO public.character_items (user_id, slot_index, stack, {_copyColumns})
                    SELECT @buyer, @slot, @q, {_copyColumns}
                    FROM public.character_items WHERE id = @id
                    RETURNING id
                    """, connection, transaction))
                {
                    copy.Parameters.AddWithValue("buyer", buyerId);
                    copy.Parameters.AddWithValue("slot", (short)slot);
                    copy.Parameters.AddWithValue("q", (short)quantity);
                    copy.Parameters.AddWithValue("id", item.InstanceId);
                    newId = await copy.ExecuteScalarAsync(cancellationToken) is long created && created > 0
                        ? created
                        : throw new InvalidOperationException("The bought part of the stack was not created.");
                }
                var after = await ReadStatesAsync(connection, transaction, [item.InstanceId, newId], cancellationToken);
                sellerEntries = [new(item.InstanceId, "update", beforeStates[item.InstanceId], after[item.InstanceId])];
                buyerEntries = [new(newId, "add", null, after[newId])];
            }

            var purchaseId = Guid.NewGuid();
            await WriteCharacterEvidenceAsync(connection, transaction, StallFamily, purchaseId,
                sellerAccountId, sellerId, buyerId, s, (int)(s.Silver + silverCost), (int)(s.Gold + goldCost),
                sellerEntries, cancellationToken);
            await WriteCharacterEvidenceAsync(connection, transaction, StallFamily, purchaseId,
                buyerAccountId, buyerId, sellerId, b, (int)(b.Silver - silverCost), (int)(b.Gold - goldCost),
                buyerEntries, cancellationToken);
            var logId = await InsertLogAsync(connection, transaction, "stall", seller, buyer, new
            {
                purchaseId,
                quantity,
                silverPerUnit,
                goldPerUnit,
                buyerSlot = slot,
                buyerItemId = buyerEntries[0].ItemInstanceId,
                split = quantity != item.Stack
            }, cancellationToken);
            await transaction.CommitAsync(cancellationToken);
            return new(PlayerTradeCommitStatus.Committed, LogId: logId);
        }
        catch (PostgresException error) when (error.SqlState is "23514" or "40001" or "40P01" or "23505")
        {
            await SafeRollbackAsync(transaction);
            return new(PlayerTradeCommitStatus.Failed, Detail: $"{error.SqlState} {error.MessageText}");
        }
        catch (Exception error) when (error is not OperationCanceledException)
        {
            await SafeRollbackAsync(transaction);
            return new(PlayerTradeCommitStatus.Failed, Detail: $"{error.GetType().Name}: {error.Message}");
        }
        finally
        {
            if (transaction is not null) await transaction.DisposeAsync();
            if (connection is not null) await connection.DisposeAsync();
        }
    }


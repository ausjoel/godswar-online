-- Minimal copy of the reborn tables the sign-up site touches, for a PRIVATE throwaway test cluster.
-- public.accounts: the columns of reborn's database/postgres/001_init.sql (the live shape the site
-- writes; later reborn migrations add more columns, which the site never touches).
-- public.character_base: only the columns the rankings view in signup-db.sql reads.
-- Run as the database owner (godswar). Never run against the live database.
CREATE TABLE IF NOT EXISTS public.accounts (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid varchar(36) NOT NULL DEFAULT '',
    email varchar(255) NOT NULL DEFAULT '',
    username varchar(32) NOT NULL,
    password varchar(255) NOT NULL DEFAULT '',
    login_status smallint NOT NULL DEFAULT 0,
    last_login_time timestamptz NOT NULL DEFAULT now(),
    last_logout_time timestamptz NOT NULL DEFAULT now(),
    last_login_ip varchar(255) NOT NULL DEFAULT '',
    last_login_mac varchar(255) NOT NULL DEFAULT '',
    total_online_time bigint NOT NULL DEFAULT 0,
    status smallint NOT NULL DEFAULT 0,
    donator_tier integer NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_accounts_username ON public.accounts (username);

CREATE TABLE IF NOT EXISTS public.character_base (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(32) NOT NULL,
    fighter_job_lv integer NOT NULL DEFAULT 1,
    profession integer NOT NULL DEFAULT 0,
    camp integer NOT NULL DEFAULT 0,
    prestige bigint NOT NULL DEFAULT 0,
    "Money" bigint NOT NULL DEFAULT 0,
    lifecycle_state varchar(16) NOT NULL DEFAULT 'active',
    "GM" integer NOT NULL DEFAULT 0
);
